import type { CollectionConfig } from 'payload'

import { hasRole, staffOrPublished } from '@/access'
import { BoardMembers } from '../../blocks/BoardMembers/config'
import { ContactInfo } from '../../blocks/ContactInfo/config'
import { CourseList } from '../../blocks/CourseList/config'
import { LegalNotice } from '../../blocks/LegalNotice/config'
import { LinkList } from '../../blocks/LinkList/config'
import { SponsorList } from '../../blocks/SponsorList/config'
import { TrainingSchedule } from '../../blocks/TrainingSchedule/config'
import { UpcomingEvents } from '../../blocks/UpcomingEvents/config'
import { Archive } from '../../blocks/ArchiveBlock/config'
import { CallToAction } from '../../blocks/CallToAction/config'
import { Content } from '../../blocks/Content/config'
import { ClubForm } from '../../blocks/ClubForm/config'
import { MediaBlock } from '../../blocks/MediaBlock/config'
import { hero } from '@/heros/config'
import { slugField } from '@/fields/slug'
import { populatePublishedAt } from '../../hooks/populatePublishedAt'
import { generatePreviewPath } from '../../utilities/generatePreviewPath'
import { revalidatePages } from '@/hooks/revalidate'

import {
  MetaDescriptionField,
  MetaImageField,
  MetaTitleField,
  OverviewField,
  PreviewField,
} from '@payloadcms/plugin-seo/fields'

export const Pages: CollectionConfig<'pages'> = {
  slug: 'pages',
  labels: { singular: 'Seite', plural: 'Seiten' },
  access: {
    create: hasRole('vorstand', 'redakteur'),
    delete: hasRole('vorstand', 'redakteur'),
    read: staffOrPublished,
    update: hasRole('vorstand', 'redakteur'),
  },
  // This config controls what's populated by default when a page is referenced
  // https://payloadcms.com/docs/queries/select#defaultpopulate-collection-config-property
  // Type safe if the collection slug generic is passed to `CollectionConfig` - `CollectionConfig<'pages'>
  defaultPopulate: {
    title: true,
    slug: true,
  },
  admin: {
    group: 'Inhalte',
    defaultColumns: ['title', 'slug', 'updatedAt'],
    livePreview: {
      url: ({ data, req }) =>
        generatePreviewPath({
          slug: data?.slug,
          collection: 'pages',
          req,
        }),
    },
    preview: (data, { req }) =>
      generatePreviewPath({
        slug: data?.slug as string,
        collection: 'pages',
        req,
      }),
    useAsTitle: 'title',
  },
  fields: [
    {
      name: 'title',
      type: 'text',
      required: true,
    },
    {
      type: 'tabs',
      tabs: [
        {
          fields: [hero],
          label: 'Hero',
        },
        {
          fields: [
            {
              name: 'layout',
              type: 'blocks',
              blocks: [
                Content,
                MediaBlock,
                CallToAction,
                TrainingSchedule,
                UpcomingEvents,
                CourseList,
                BoardMembers,
                SponsorList,
                LinkList,
                ContactInfo,
                LegalNotice,
                Archive,
                ClubForm,
              ],
              required: true,
              admin: {
                initCollapsed: true,
              },
            },
          ],
          label: 'Content',
        },
        {
          name: 'meta',
          label: 'SEO',
          fields: [
            OverviewField({
              titlePath: 'meta.title',
              descriptionPath: 'meta.description',
              imagePath: 'meta.image',
            }),
            MetaTitleField({
              hasGenerateFn: true,
            }),
            MetaImageField({
              relationTo: 'media',
            }),

            MetaDescriptionField({}),
            PreviewField({
              // if the `generateUrl` function is configured
              hasGenerateFn: true,

              // field paths to match the target field for data
              titlePath: 'meta.title',
              descriptionPath: 'meta.description',
            }),
          ],
        },
      ],
    },
    {
      name: 'publishedAt',
      type: 'date',
      admin: {
        position: 'sidebar',
      },
    },
    slugField(),
  ],
  hooks: {
    afterChange: [revalidatePages.afterChange],
    beforeChange: [populatePublishedAt],
    afterDelete: [revalidatePages.afterDelete],
  },
  versions: {
    drafts: {
      autosave: {
        interval: 100, // We set this interval for optimal live preview
      },
      schedulePublish: true,
    },
    maxPerDoc: 50,
  },
}
